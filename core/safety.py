"""Conservative local routing rules. No diagnosis, treatment or real transfer."""
import re

RULES = (
    r'\bоператор\w*', r'\b(?:жив\w+\s+(?:человек\w*|сотрудник\w*)|человек\w*|сотрудник\w*|администратор\w*)',
    r'\b(?:жалоб\w*|пожалова\w*|претензи\w*)',
    r'\b(?:боль|боли|болью|больно|болит|болят|болезн\w*|болев\w*)\b',
    r'\b(?:задыха\w*|кровотеч\w*|инфаркт\w*|инсульт\w*|неотлож\w*)',
    r'\b(?:скорая|скорую|срочно|срочная|экстренн\w*)\b',
    r'\bне\s+могу\s+дышать\b', r'\bпотер\w*\s+сознани\w*',
    r'\b(?:лекарств\w*|диагноз\w*|симптом\w*|лечени\w*|лечить|лечиться|таблет\w*|антибиотик\w*|дозировк\w*)',
    r'\b(?:как|чем)\s+леч\w*', r'\bчто\s+(?:принимать|выпить|пить)\b',
    r'\b(?:температур\w*|кашель|кашля\w*|сыпь|тошнит|рвота|давление)\b',
    r'\b(?:отменить\s+запись|перенести\s+запись|статус\s+записи|стоимость|оплата|справка|результат\w*\s+анализ\w*)\b',
)
_patterns = tuple(re.compile(rule) for rule in RULES)


def handoff(text: str) -> bool:
    value = text.lower().replace('ё', 'е')
    return any(pattern.search(value) for pattern in _patterns)


