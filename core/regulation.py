@dataclass
class Route:
    kind: str
    message: str
    rule: str


def _current_match(patterns, text):
    clauses = re.split(r'[.;!?]|\b(?:но|сейчас)\b',text)
    for clause in clauses:
        if re.search(r'в прошлом|в детстве|раньше|год назад|вчера.*(?:прошл|был)',clause):
            continue
        if re.search(r'(?:нет|не было|без)\s+(?:сильной\s+)?бол[ьи]\s+в груди',clause):
            continue
        if any(re.search(p,clause) for p in patterns): return True
    return False


def route(text, now):
    t=' '.join(text.lower().replace('ё','е').split())
    if _current_match(A,t):
        return Route('emergency','Позвоните 103 или 112 сейчас. Запись остановлена. Демо не соединяет с экстренными службами.','R-01')
    if _current_match(B,t):
        open_hours=(now.weekday()<5 and 7<=now.hour<20) or (now.weekday()==5 and (now.hour,now.minute)>=(8,30) and now.hour<15)
        message='Нужен сотрудник для срочной помощи. При ухудшении звоните 103. Карточка передачи сформирована (демо); соединение не выполняется.' if open_hours else 'Регистратура закрыта. Позвоните 103. Карточка срочной передачи сформирована (демо); соединение не выполняется.'
        return Route('urgent',message,'R-11')
    if re.search(r'\b(?:жалоб\w*|пожалова\w*|претензи\w*)',t):
        return Route('complaint','Нужна помощь старшего администратора. Карточка передачи сформирована (демо); фактическое соединение не выполняется.','R-03')
    if re.search(r'\b(?:оператор\w*|человек\w*|сотрудник\w*|регистратор\w*|живой|живым|соедините)\b',t):
        return Route('operator','Карточка передачи оператору сформирована (демо). Пожалуйста, свяжитесь с сотрудником напрямую; соединение не выполняется.','R-02')
    if re.search(r'\b(?:болит|боль|боли|болезн\w*|лекарств\w*|диагноз\w*|лечить|лечени\w*|температур\w*|таблет\w*|кашель|сыпь)\b|что (?:пить|выпить|принимать)|как леч',t):
        return Route('medical','Медицинские советы даёт врач. Карточка передачи сотруднику сформирована (демо); фактическое соединение не выполняется.','R-04')
    if re.search(r'\b(?:моей мам|моего пап|мою мам|моего ребен|за мужа|за жен|за ребен|другого человека|на когда записана)\w*',t):
        return Route('privacy','Сведения о чужих записях не сообщаю. Нужна проверка полномочий сотрудником; карточка передачи сформирована (демо).','R-07')
    return None


